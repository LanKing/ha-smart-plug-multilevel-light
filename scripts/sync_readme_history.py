#!/usr/bin/env python3
from __future__ import annotations

import re
from pathlib import Path

PATH = Path(__file__).resolve().parents[1] / "README_RU.md"


def main() -> None:
    text = PATH.read_text(encoding="utf-8")

    text = text.replace("version-0.6.4-blue", "version-0.9.0-blue")
    text = text.replace("Version 0.6.4", "Version 0.9.0")
    text = text.replace("?v=0.6.4", "?v=0.9.0")

    text = text.replace(
        "* Автоматически предлагает порог режима с запасом относительно измеренного тока, чтобы небольшие колебания потребления не мешали его определению;\n",
        "",
    )
    text = text.replace(
        "* Автоматически определяет текущий режим работы светильника по фактически измеренному току;",
        "* Определяет текущий режим по наиболее часто встречающемуся настроенному значению среди последних показаний тока, отбрасывая остальные значения;",
    )
    text = text.replace(
        "* Использует нелинейную шкалу яркости с округлением до 5%, лучше отражающую различия между режимами;",
        "* Использует нелинейную шкалу яркости; округление рассчитанной яркости до 5% можно включать и отключать;",
    )
    text = text.replace(
        "* Позволяет настроить порог тока, ниже которого светильник считается выключенным;\n",
        "",
    )

    text = re.sub(r"^\s*- \*\*OFF current threshold\*\*.*\n", "", text, flags=re.MULTILINE)
    text = text.replace(
        "   - **Power cycle delay** — пауза между отключением и повторной подачей питания; по умолчанию `0.7 s`;",
        "   - **Power cycle delay** — пауза между отключением и повторной подачей питания; по умолчанию `0.7 s`;\n"
        "   - **Recent current readings** — количество последних показаний, участвующих в выборе режима; по умолчанию `5`;\n"
        "   - **Round brightness to 5%** — округление рассчитанной яркости до 5%; по умолчанию включено;",
    )
    text = text.replace(
        "   - **Brightness modes** — добавьте минимум один режим яркости и соответствующий ему ток.",
        "   - **Brightness modes** — добавьте минимум один режим яркости и точное значение тока для него.",
    )
    text = text.replace(
        "- если розетка включена, но лампа была выключена собственной кнопкой и ток упал до **OFF current threshold** или ниже, команда включения должна кратко отключить розетку, подождать **Power cycle delay** и включить её снова.",
        "- если розетка включена, но лампа была выключена собственной кнопкой и ток равен `0 A`, команда включения должна кратко отключить розетку, подождать **Power cycle delay** и включить её снова.",
    )

    text = re.sub(r"^\| \*\*OFF current threshold\*\*.*\n", "", text, flags=re.MULTILINE)
    marker = "| **Power cycle delay** | пауза между выключением и повторным включением розетки | `0.7 s` |"
    if marker in text and "| **Recent current readings**" not in text:
        text = text.replace(
            marker,
            marker + "\n| **Recent current readings** | количество последних показаний тока для выбора режима | `5` |\n"
            "| **Round brightness to 5%** | округление рассчитанной яркости до ближайших 5% | включено |",
        )

    text = re.sub(
        r"\n### Как подобрать OFF threshold\n.*?(?=\n### )",
        "\n",
        text,
        flags=re.DOTALL,
    )
    text = text.replace("### Как подобрать пороги режимов", "### Как задать значения режимов")
    text = text.replace("| Режим | Порог тока |", "| Режим | Ток |")
    text = text.replace(
        "В подписи поля порога отображается текущее измеренное значение выбранного датчика тока. Это упрощает настройку без перехода на отдельную страницу сущности.",
        "В редакторе режима отображается текущее измеренное значение выбранного датчика тока. Его можно применить напрямую: режимы сравниваются с показаниями с точностью до `0.001 A`.",
    )

    text = re.sub(
        r"Режим выбирается по правилу: используется максимальный настроенный порог, который меньше или равен измеренному току\..*?(?=\n## 🔌 Как определяется состояние)",
        "Режим определяется по истории последних показаний. Сначала интеграция оставляет только значения, которые точно совпадают с одним из настроенных значений режима с точностью до `0.001 A`. Затем выбирается значение, встретившееся чаще всего. При равенстве количества побеждает более свежее значение. Размер окна задаётся параметром **Recent current readings**, по умолчанию `5`.\n",
        text,
        flags=re.DOTALL,
    )

    text = re.sub(
        r"Виртуальная лампа считается включённой, только когда одновременно выполняются два условия:\n\n1\. розетка находится в состоянии `on`;\n2\..*?\n\nСледовательно,.*?(?=\n\nЕсли розетка или датчик тока)",
        "Виртуальная лампа считается включённой, только когда одновременно выполняются два условия:\n\n1. розетка находится в состоянии `on`;\n2. измеренный ток строго выше `0 A`.\n\nЗначения тока, не совпадающие с настроенными режимами, не используются для определения режима, но сами по себе не переводят сущность в OFF.",
        text,
        flags=re.DOTALL,
    )

    text = text.replace(
        "| Розетка `on`, но ток не выше **OFF current threshold** | выключает розетку, ждёт **Power cycle delay**, затем включает её снова |",
        "| Розетка `on`, но ток равен `0 A` | выключает розетку, ждёт **Power cycle delay**, затем включает её снова |",
    )

    text = text.replace("`measured_current` | текущее значение датчика тока |", "`measured_current` | текущее значение датчика тока |")

    text = re.sub(
        r"### Лампа отображается как OFF при включённой розетке\n\n.*?(?=\n### )",
        "### Лампа отображается как OFF при включённой розетке\n\nПроверьте датчик тока. При включённой розетке виртуальная лампа считается OFF только при токе `0 A`.\n",
        text,
        flags=re.DOTALL,
    )
    text = re.sub(
        r"### Лампа отображается как ON, когда физически выключена\n\n.*?(?=\n### )",
        "### Лампа отображается как ON, когда физически выключена\n\nПроверьте, что датчик тока действительно возвращает `0 A` при выключенной лампе. Отдельного OFF-порога интеграция не использует.\n",
        text,
        flags=re.DOTALL,
    )
    text = re.sub(
        r"### Определяется неправильный режим\n\n.*?(?=\n### )",
        "### Определяется неправильный режим\n\nПроверьте атрибуты `current_history`, `valid_current_history` и `selected_current`. В режиме участвуют только показания, точно совпавшие с настроенными значениями с точностью до `0.001 A`; остальные показания отбрасываются.\n",
        text,
        flags=re.DOTALL,
    )

    text = text.replace(
        "- Значение датчика тока должно быть числовым и фактически выражаться в амперах, соответствующих порогам настройки.",
        "- Значение датчика тока должно быть числовым и выражаться в амперах; для определения режима сравнение выполняется с точностью до `0.001 A`.",
    )

    PATH.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
