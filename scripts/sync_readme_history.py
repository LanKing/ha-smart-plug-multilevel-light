#!/usr/bin/env python3
from __future__ import annotations

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATH = ROOT / "README_RU.md"
POWER_BASELINE = "0d32c707f3d5ec45fa9009a07a98ab7d2cd8964c"


def main() -> None:
    text = subprocess.check_output(
        ["git", "show", f"{POWER_BASELINE}:README_RU.md"],
        cwd=ROOT,
        text=True,
        encoding="utf-8",
    )

    text = text.replace("version-0.6.4-blue", "version-0.9.0-blue")
    text = text.replace("Version 0.6.4", "Version 0.9.0")
    text = text.replace("?v=0.6.4", "?v=0.9.0")

    text = text.replace(
        "* Автоматически определяет текущий режим работы светильника по фактически измеренной мощности;",
        "* Фиксирует последние показания мощности и определяет режим по значению, которое встречалось в этом окне чаще всего;",
    )
    text = text.replace(
        "* Использует нелинейную шкалу яркости с округлением до 5%, лучше отражающую различия между режимами;",
        "* Использует нелинейную шкалу яркости; округление рассчитанной яркости до 5% можно включать и отключать;",
    )

    text = text.replace(
        "   - **Power cycle delay** — пауза между отключением и повторной подачей питания; по умолчанию `0.7 s`;",
        "   - **Power cycle delay** — пауза между отключением и повторной подачей питания; по умолчанию `0.7 s`;\n"
        "   - **Recent power readings** — количество последних показаний мощности, используемых для выбора режима; по умолчанию `5`;\n"
        "   - **Round brightness to 5%** — округление рассчитанной яркости до 5%; по умолчанию включено;",
    )

    marker = "| **Power cycle delay** | пауза между выключением и повторным включением розетки | `0.7 s` |"
    if marker in text and "| **Recent power readings**" not in text:
        text = text.replace(
            marker,
            marker + "\n| **Recent power readings** | количество последних показаний мощности для выбора режима | `5` |\n"
            "| **Round brightness to 5%** | округление рассчитанной яркости до ближайших 5% | включено |",
        )

    text = re.sub(
        r"Режим выбирается по правилу: используется максимальный настроенный порог, который меньше или равен измеренной мощности\..*?(?=\n## 🔌 Как определяется состояние)",
        "Для определения режима интеграция хранит последние **N** показаний мощности, где **N** задаётся параметром **Recent power readings** и по умолчанию равно `5`. Из этого окна выбирается значение мощности, встретившееся чаще всего. Если несколько значений встречались одинаковое количество раз, используется самое свежее из них. После этого к выбранному значению применяется обычная пороговая логика: используется максимальный настроенный порог, который меньше или равен выбранной мощности. Поэтому промежуточные значения между порогами продолжают нормально определять режим.\n",
        text,
        flags=re.DOTALL,
    )

    text = re.sub(
        r"### Определяется неправильный режим\n\n.*?(?=\n### )",
        "### Определяется неправильный режим\n\nПроверьте атрибуты `power_history` и `selected_power`. В `power_history` находятся последние показания мощности, а `selected_power` — наиболее часто встречавшееся значение, по которому затем выбирается режим согласно настроенным порогам.\n",
        text,
        flags=re.DOTALL,
    )

    PATH.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
